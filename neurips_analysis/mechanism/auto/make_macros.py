# ---------------------------------------------------------------- accuracies and paired differences
random.seed(20261011)


def per_item(m, protos, headcols=()):
    g = defaultdict(list)
    for p in protos:
        # Preserve the three spliced May run rows, including their shared
        # long-output trajectories, when averaging runs within each item.
        for d in R[(m, p)]:
            g[d['item_id']].append(int(bool(d['correct'])))
    for col in headcols:
        for i in ver:
            g[i].append(int(head[m][i][col]))
    return g


def diff_vec(a, b):
    ids = sorted(i for i in ver if a.get(i) and b.get(i))
    return [sum(a[i]) / len(a[i]) - sum(b[i]) / len(b[i]) for i in ids]


def boot(dv, B=4000):
    n = len(dv)
    o = sorted(sum(dv[random.randrange(n)] for _ in range(n)) / n * 100 for _ in range(B))
    return o[int(0.025 * B)], o[int(0.975 * B) - 1]


def signflip_p(dv, B=20000):
    obs = abs(sum(dv))
    hit = sum(1 for _ in range(B) if abs(sum(x if random.random() < 0.5 else -x for x in dv)) >= obs - 1e-12)
    return (hit + 1) / (B + 1)


def dmac(name, dv, comment=None):
    lo, hi = boot(dv)
    est = 100 * sum(dv) / len(dv)
    mac(name, '%s\\,pp [%s, %s]' % (signed(est), signed(lo), signed(hi)), comment)
    mac(name + 'P', signed(est))
    return est


