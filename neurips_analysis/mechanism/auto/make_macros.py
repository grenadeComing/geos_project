# ---------------------------------------------------------------- Shapley (summary 2c)
def shapley_rows(subset_title):
    s = [i for i, l in enumerate(summary) if l.strip() == '*Subset: %s*' % subset_title][0] + 4
    out = {}
    while s < len(summary) and summary[s].startswith('|'):
        c = [x.strip() for x in summary[s].strip('|').split('|')]
        out[(c[0], c[1])] = c[2:7]
        s += 1
    return out


def fmt_ci(cell):
    m = re.match(r'([-+]\d+\.\d) \[([-+]\d+\.\d), ([-+]\d+\.\d)\]', cell)
    a, lo, hi = (float(x) for x in m.groups())
    return signed(a), '%s [%s, %s]' % (signed(a), signed(lo), signed(hi))


